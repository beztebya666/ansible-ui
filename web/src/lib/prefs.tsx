export function PrefsProvider({ children }: { children: ReactNode }) {
  const [theme, setThemeState] = useState<Theme>(
    () => (localStorage.getItem("aui.theme") as Theme) || "dark",
  );
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("aui.lang") as Lang) || "en");
  const [tz, setTzState] = useState<string>(() => localStorage.getItem("aui.tz") || "");
  const [clock, setClockState] = useState<Clock>(() => (localStorage.getItem("aui.clock") as Clock) || "24h");

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    localStorage.setItem("aui.theme", theme);
  }, [theme]);
  useEffect(() => {
    document.documentElement.lang = lang;
    localStorage.setItem("aui.lang", lang);
  }, [lang]);

  const setTz = useCallback((s: string) => {
    setTzState(s);
    if (s) localStorage.setItem("aui.tz", s);
    else localStorage.removeItem("aui.tz");
  }, []);

  const setClock = useCallback((c: Clock) => {
    setClockState(c);
    localStorage.setItem("aui.clock", c);
  }, []);

  // Write synchronously (not only in the effect) so any localStorage-reading
  // formatter sees the new language on the very next render, with no lag.
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("aui.lang", l);
  }, []);

  const t = useCallback(
    (key: string) => dict[lang][key] ?? dict.en[key] ?? key,
    [lang],
  );

  return (
    <Ctx.Provider
      value={{
        theme,
        setTheme: setThemeState,
        toggleTheme: () => setThemeState((p) => (p === "dark" ? "light" : "dark")),
        lang,
        setLang,
        tz,
        setTz,
        clock,
        setClock,
        t,
      }}
    >
      {children}
    </Ctx.Provider>
  );
}

export function usePrefs(): Prefs {
  const c = useContext(Ctx);
  if (!c) throw new Error("usePrefs must be used within PrefsProvider");
  return c;
}
